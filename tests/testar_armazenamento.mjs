import assert from "node:assert/strict";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { criarArmazenamento } from "../painel/armazenamento-sinais.mjs";
import { cadastro } from "./apoio-gestos.mjs";
const { IDBFactory } = await import(pathToFileURL(resolve(process.argv[2], "node_modules/fake-indexeddb/build/esm/index.js")));
const indexado = new IDBFactory();
const a = criarArmazenamento(indexado), b = criarArmazenamento(indexado);
const gabriel = cadastro(), ana = cadastro("Ana", 1.5);
await a.salvar(gabriel);
assert.equal((await b.listar())[0].nome, "Gabriel", "outro cliente lê o cadastro persistido");
await b.salvar({ ...gabriel, nome: "Gabi", ativo: false });
assert.equal((await a.listar())[0].ativo, false);
const dadosCorrompidos = { ...cadastro("Inválido", 3), confirmacao: [] };
await assert.rejects(a.importar([ana, dadosCorrompidos]));
assert.equal((await a.listar()).length, 1, "importação inválida não grava parte do arquivo");
const concorrentes = await Promise.allSettled([a.salvar(ana), b.salvar({ ...ana, id: "outro-id" })]);
assert.equal(concorrentes.filter((r) => r.status === "fulfilled").length, 1, "transações concorrentes não duplicam o nome");
await a.excluir(gabriel.id);
assert.equal((await b.listar()).length, 1);
assert.equal((await criarArmazenamento(indexado).listar())[0].nome, "Ana");
console.log("IndexedDB: persistência entre clientes, edição, exclusão, importação atômica e concorrência passaram (fake-indexeddb; não é Chrome).");
